package src;

public class EscapeSequence {
    public static void main(String[] args) {
        System.out.println("Hello 'KGCoding'....");
        System.out.println("Hello \"KGCoding\"....");
        System.out.println("Hello \\KGCoding\\....");
        System.out.println("Hello \nKGCoding....");
        System.out.println("Hello KG\tCoding....");
        System.out.println("Hello\bKGCoding....");

    }
}
